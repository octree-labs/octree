CREATE OR REPLACE FUNCTION "public"."increment_edit_count"("p_user_id" "uuid") RETURNS boolean
    LANGUAGE "plpgsql" SECURITY DEFINER
    AS $$
DECLARE
  current_edit_count INTEGER;
  current_monthly_count INTEGER;
  current_daily_reset DATE;
  user_monthly_reset DATE;
  is_pro_user BOOLEAN;
  max_free_daily_edits INTEGER := 5;
  max_pro_monthly_edits INTEGER := 500;
BEGIN
  -- Get current usage
  SELECT edit_count, monthly_edit_count, daily_reset_date, monthly_reset_date, is_pro 
  INTO current_edit_count, current_monthly_count, current_daily_reset, user_monthly_reset, is_pro_user
  FROM public.user_usage
  WHERE user_id = p_user_id;
  
  -- If user is pro, check monthly reset and limit
  IF is_pro_user THEN
    -- Check if monthly reset is needed
    IF CURRENT_DATE >= user_monthly_reset THEN
      UPDATE public.user_usage
      SET 
        monthly_edit_count = 0,
        monthly_reset_date = (CURRENT_DATE + INTERVAL '1 month')::date,
        updated_at = now()
      WHERE user_id = p_user_id;
      
      current_monthly_count := 0;
    END IF;
    
    -- Check monthly limit
    IF current_monthly_count >= max_pro_monthly_edits THEN
      RETURN FALSE; -- Monthly limit reached
    END IF;
    
    -- Increment monthly count
    UPDATE public.user_usage
    SET 
      monthly_edit_count = monthly_edit_count + 1,
      updated_at = now()
    WHERE user_id = p_user_id;
  ELSE
    -- Free user: check daily reset and limit
    -- Check if daily reset is needed
    IF CURRENT_DATE > current_daily_reset THEN
      UPDATE public.user_usage
      SET 
        edit_count = 0,
        daily_reset_date = CURRENT_DATE,
        updated_at = now()
      WHERE user_id = p_user_id;
      
      current_edit_count := 0;
    END IF;
    
    -- Check daily limit
    IF current_edit_count >= max_free_daily_edits THEN
      RETURN FALSE; -- Daily limit reached
    END IF;
    
    -- Increment daily count
    UPDATE public.user_usage
    SET 
      edit_count = edit_count + 1,
      updated_at = now()
    WHERE user_id = p_user_id;
  END IF;
  
  RETURN TRUE;
END;
$$;


ALTER FUNCTION "public"."increment_edit_count"("p_user_id" "uuid") OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."update_user_subscription_status"("p_user_id" "uuid", "p_stripe_customer_id" "text", "p_stripe_subscription_id" "text", "p_subscription_status" "text", "p_current_period_start" timestamp with time zone, "p_current_period_end" timestamp with time zone, "p_cancel_at_period_end" boolean) RETURNS "void"
    LANGUAGE "plpgsql" SECURITY DEFINER
    AS $$
BEGIN
  UPDATE public.user_usage
  SET 
    stripe_customer_id = p_stripe_customer_id,
    stripe_subscription_id = p_stripe_subscription_id,
    subscription_status = p_subscription_status,
    current_period_start = p_current_period_start,
    current_period_end = p_current_period_end,
    cancel_at_period_end = p_cancel_at_period_end,
    is_pro = CASE 
      WHEN p_subscription_status IN ('active', 'trialing') THEN TRUE
      ELSE FALSE
    END,
    -- Reset monthly count when subscription becomes active
    monthly_edit_count = CASE 
      WHEN p_subscription_status IN ('active', 'trialing') THEN 0
      ELSE monthly_edit_count
    END,
    monthly_reset_date = CASE 
      WHEN p_subscription_status IN ('active', 'trialing') THEN (CURRENT_DATE + INTERVAL '1 month')::date
      ELSE monthly_reset_date
    END,
    updated_at = now()
  WHERE user_id = p_user_id;
END;
$$;


