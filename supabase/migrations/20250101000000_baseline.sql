CREATE OR REPLACE FUNCTION "public"."admin_daily_signups"() RETURNS TABLE("signup_date" "date", "new_signups" bigint)
    LANGUAGE "sql" SECURITY DEFINER
    AS $$
  SELECT
    DATE(created_at) AS signup_date,
    COUNT(id) AS new_signups
  FROM auth.users
  WHERE created_at >= NOW() - INTERVAL '90 days'
  GROUP BY signup_date
  ORDER BY signup_date ASC;
$$;


ALTER FUNCTION "public"."admin_daily_signups"() OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."admin_weekly_signups"() RETURNS TABLE("signup_week" timestamp with time zone, "new_signups" bigint)
    LANGUAGE "sql" SECURITY DEFINER
    AS $$
  SELECT
    DATE_TRUNC('week', created_at) AS signup_week,
    COUNT(id) AS new_signups
  FROM auth.users
  WHERE created_at >= NOW() - INTERVAL '90 days'
  GROUP BY signup_week
  ORDER BY signup_week DESC;
$$;


ALTER FUNCTION "public"."admin_weekly_signups"() OWNER TO "postgres";


